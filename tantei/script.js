// --- 判定用のゾーン計算 ---
// 座標(x,y)がゾーンの内側か
function inZone(z, x, y) {
  return x >= z.xMin && x <= z.xMax && y >= z.yMin && y <= z.yMax;
}

// ゾーンまでの距離（％）。内側なら0。「惜しい」の判定に使う。
function zoneDistance(z, x, y) {
  const dx = Math.max(z.xMin - x, 0, x - z.xMax);
  const dy = Math.max(z.yMin - y, 0, y - z.yMax);
  return Math.hypot(dx, dy);
}

// 旧形式（target 1つ）のデータでも動くようにしておく
function targetsOf(stage) {
  if (stage.targets && stage.targets.length) return stage.targets;
  return stage.target ? [stage.target] : [];
}

// --- 正解判定 ---
function confirmAccusation() {
  if (accuseCooldown > 0) return;

  const stage = stages[currentStageIndex];

  // --- 供述型 ---
  if (isStatementMode(stage)) {
    if (selectedSuspect === null) return;
    const sus = stage.suspects[selectedSuspect];
    if (sus && sus.lie) {
      handleCorrect();
    } else {
      stageMistakes++;
      SoundManager.play("wrong");
      triggerHaptics([180, 100, 180]);
      triggerScreenShake();
      if (clearedSuspect === null) {
        // 1回目だけ、外した供述を畳んで残り2枚に絞る。
        // 「どこを読み直せばいいか」が分かれば、もう一度読む気になる。
        clearedSuspect = selectedSuspect;
        const card = suspectListEl.children[selectedSuspect];
        if (card) { card.classList.add("cleared"); card.classList.remove("selected"); }
        showToast(shortNameOf(sus) + "の供述に、現場と食い違う点はない。残る2人を読み比べよう。", "near");
      } else {
        showToast("その供述も現場と食い違っていない。資料をもう一度見てほしい。", "near");
      }
      selectedSuspect = null;
      startAccuseCooldown();
    }
    return;
  }

  // --- 従来のタップ型 ---
  // ボタンは disabled のはずだが、キー操作等で先に来ても誤判定しないようにする
  if (selectedX === null || selectedY === null) return;
  const zones = targetsOf(stage);
  const hit = zones.some(z => inZone(z, selectedX, selectedY));

  if (hit) {
    handleCorrect();
    return;
  }

  // --- 不正解 ---
  stageMistakes++;
  SoundManager.play("wrong");
  triggerHaptics([180, 100, 180]);
  triggerScreenShake();

  const pinRect = tapPinEl.getBoundingClientRect();
  spawnWrongRipple(pinRect.left + pinRect.width / 2, pinRect.top + pinRect.height / 2);

  // ダミー（誘導）ゾーンなら、なぜ違うのかを返す。
  // 「違います」だけを返し続けると、プレイヤーは推理をやめて総当たりに移る。
  let msg = null;
  let kind = "";
  const decoys = stage.decoys || [];
  for (let i = 0; i < decoys.length; i++) {
    if (inZone(decoys[i].zone, selectedX, selectedY)) {
      msg = decoys[i].msg;
      kind = "near";
      break;
    }
  }
  if (msg === null) {
    let nearest = Infinity;
    for (let i = 0; i < zones.length; i++) {
      nearest = Math.min(nearest, zoneDistance(zones[i], selectedX, selectedY));
    }
    if (nearest <= NEAR_MISS_PCT) {
      msg = "惜しい！ごく近くです。その周辺をもう一度よく見てください。";
      kind = "near";
    } else {
      msg = "違います。画像を拡大してよく観察してください。";
    }
  }
  showToast(msg, kind);
  startAccuseCooldown();
}

function handleCorrect() {
  SoundManager.play("correct");
  triggerHaptics([50, 50, 50]);

  const stageNow = stages[currentStageIndex];
  if (isStatementMode(stageNow)) {
    // シートを閉じて写真を露わにしてから、食い違っていた箇所を大きく示す
    hideSheet();
    setTimeout(() => {
      showEvidenceFrame();
      const f = document.getElementById("evidence-frame");
      if (f) {
        const r = f.getBoundingClientRect();
        spawnGoldParticles(r.left + r.width / 2, r.top + r.height / 2);
      }
    }, 160);
  } else {
    const pinRect = tapPinEl.getBoundingClientRect();
    spawnGoldParticles(pinRect.left + pinRect.width / 2, pinRect.top + pinRect.height / 2);
  }

  const elapsedSeconds = Math.floor((Date.now() - stageStartTime) / 1000);

  // 星：ノーミスかつヒント無しで3。ヒントもミスも減点対象。
  let stars = 3;
  if (hintUsed && HINT_COSTS_STAR) stars--;
  if (stageMistakes > 0) stars--;
  if (stageMistakes > 2) stars--;
  stars = Math.max(1, stars);

  const timeText = elapsedSeconds < 60
    ? `${elapsedSeconds}秒`
    : `${Math.floor(elapsedSeconds / 60)}分${elapsedSeconds % 60}秒`;

  lastClearStars = stars;
  clearedStageRecords[currentStageIndex] = {
    cleared: true,
    time: timeText,
    stars: stars,
    mistakes: stageMistakes,
    hint: hintUsed
  };

  if (currentStageIndex === unlockedStageIndex && unlockedStageIndex < stages.length - 1) {
    unlockedStageIndex = currentStageIndex + 1;
  }
  saveProgress();

  cancelAccuseCooldown();
  updateAccuseButton();

  // 推理型は証拠を全画面で見せる時間を取る
  setTimeout(() => {
    SoundManager.play("clear");
    showSuccess(stars, timeText, stageMistakes);
  }, isStatementMode(stageNow) ? 1600 : 700);
}

// --- 誤答クールダウン ---
// 誤答のたびに待ち時間を伸ばす。画面を塗りつぶすように連打すれば必ず当たる、
// という攻略を成立させないための最小限の歯止め。
function startAccuseCooldown() {
  accuseCooldown = Math.min(2 + stageMistakes, 6);
  updateAccuseButton();
  if (accuseCooldownTimer) clearInterval(accuseCooldownTimer);
  accuseCooldownTimer = setInterval(() => {
    accuseCooldown--;
    updateAccuseButton();
    if (accuseCooldown <= 0) cancelAccuseCooldown();
  }, 1000);
}

function cancelAccuseCooldown() {
  if (accuseCooldownTimer) clearInterval(accuseCooldownTimer);
  accuseCooldownTimer = null;
  accuseCooldown = 0;
}

function updateAccuseButton() {
  const stage = stages[currentStageIndex];
  const statementMode = isStatementMode(stage);

  if (accuseCooldown > 0) {
    btnAccuseEl.disabled = true;
    btnAccuseEl.classList.add("cooling");
    if (accuseLabelEl) accuseLabelEl.textContent = `再考まで ${accuseCooldown}`;
    return;
  }
  btnAccuseEl.classList.remove("cooling");

  if (statementMode) {
    if (accuseLabelEl) accuseLabelEl.textContent = "この人物を告発";
    btnAccuseEl.disabled = (selectedSuspect === null);
  } else {
    if (accuseLabelEl) accuseLabelEl.textContent = "指摘する";
    btnAccuseEl.disabled = (selectedX === null || selectedY === null);
  }
}

// --- モバイル振動 (Web Haptics) ---
function triggerHaptics(pattern) {
  // デスクトップや iOS Safari には navigator.vibrate が存在しない。
  // 存在しても、ユーザー操作外・非セキュアコンテキスト・iframe 内などで例外を投げる
  // 実装があるため、判定だけでなく呼び出しも包む。
  if (typeof navigator === "undefined" || typeof navigator.vibrate !== "function") return;
  try {
    navigator.vibrate(pattern);
  } catch (e) { /* 振動できないだけ。進行には影響させない */ }
}

// --- 不正解時の画面揺れエフェクト ---
function triggerScreenShake() {
  gameContainerEl.classList.remove("shake");
  void gameContainerEl.offsetWidth; 
  gameContainerEl.classList.add("shake");
  setTimeout(() => {
    gameContainerEl.classList.remove("shake");
  }, 400);
}

// --- 不正解時の「×」マーク赤波紋エフェクト ---
function spawnWrongRipple(x, y) {
  const ripple = document.createElement("div");
  ripple.className = "wrong-ripple";
  ripple.style.left = `${x}px`;
  ripple.style.top = `${y}px`;
  ripple.innerHTML = "×";
  document.body.appendChild(ripple);

  setTimeout(() => {
    ripple.remove();
  }, 800);
}

// --- 正解時の金色粒子エフェクト ---
function spawnGoldParticles(x, y) {
  const pContainer = document.createElement("div");
  pContainer.className = "particle-container";
  document.body.appendChild(pContainer);

  const particleCount = 28;
  const colors = ["#f1c40f", "#f39c12", "#ffdf7a", "#fff", "#e74c3c"];

  for (let i = 0; i < particleCount; i++) {
    const p = document.createElement("div");
    p.className = "particle";

    const size = Math.random() * 7 + 4; 
    const angle = Math.random() * Math.PI * 2;
    const distance = Math.random() * 110 + 30; 
    const dx = Math.cos(angle) * distance;
    const dy = Math.sin(angle) * distance;

    const color = colors[Math.floor(Math.random() * colors.length)];

    p.style.setProperty("--size", `${size}px`);
    p.style.setProperty("--dx", `${dx}px`);
    p.style.setProperty("--dy", `${dy}px`);
    p.style.setProperty("--color", color);
    
    p.style.left = `${x}px`;
    p.style.top = `${y}px`;

    pContainer.appendChild(p);
  }

  setTimeout(() => {
    pContainer.remove();
  }, 1000);
}

// --- 正解モーダルの表示 ---
function showSuccess(stars, timeText, mistakes) {
  isModalOpen = true;
  successModalEl.classList.add("active");
  explanationTextEl.textContent = stages[currentStageIndex].answer;

  // 星のシーケンシャルアニメーション
  successStarsEl.innerHTML = "";
  for (let i = 0; i < 3; i++) {
    const star = document.createElement("span");
    star.className = `star-icon ${i < stars ? "star-active" : ""}`;
    star.textContent = "★";
    successStarsEl.appendChild(star);
  }

  // ここで初めて事件名がつく。ヘッダーの表記も同時に開く。
  if (solvedCaseNameEl) solvedCaseNameEl.textContent = caseNameOf(stages[currentStageIndex]);
  stageTitleEl.textContent = stages[currentStageIndex].title;

  clearTimeValEl.textContent = timeText;
  clearMistakesValEl.textContent = `${mistakes}回${hintUsed ? "（ヒント使用）" : ""}`;

  if (currentStageIndex === stages.length - 1) {
    btnNextEl.textContent = "全事件を解決した";
  } else if (IS_WEB_EDITION && !isPlayable(currentStageIndex + 1)) {
    btnNextEl.textContent = "続きはアプリで（無料・全" + stages.length + "話）";
  } else {
    btnNextEl.textContent = "次の事件へ";
  }

  // 以前は window.location.href を付けていたが、アプリ内では capacitor://localhost になり
  // 誰も開けないリンクを送っていた。送るのはブラウザ版のその話の入口。
  const solvedIndex = currentStageIndex;
  btnShareXEl.onclick = () => {
    SoundManager.play("tap");
    Challenge.send(solvedIndex, stars);
  };
}

// 正解モーダルを閉じたあとの共通処理。評価をお願いした回は全画面広告を見送る。
function afterSuccessClosed() {
  if (!Review.maybeAsk(lastClearStars)) Ads.maybeShowInterstitial();
}

// --- 次のステージへ進む ---
function handleNextStage() {
  successModalEl.classList.remove("active");
  isModalOpen = false;

  // 1ステージ クリアごとに1回、画面の切り替わりに合わせて全画面広告。
  // ゲーム中や起動直後に割り込ませないこと（AdMob のポリシー違反になる）。
  afterSuccessClosed();

  if (currentStageIndex === stages.length - 1) {
    showLobbyView();
  } else if (IS_WEB_EDITION && !isPlayable(currentStageIndex + 1)) {
    openAppStore();
    showLobbyView();
  } else {
    currentStageIndex++;
    loadStage(currentStageIndex);
  }
}

// --- 進行状況リセット ---
function handleReset() {
  unlockedStageIndex = 0;
  clearedStageRecords = {};
  saveProgress();
  renderLobby();
  showToast("捜査情報をリセットしました。");
}

// --- トースト通知 ---
function showToast(message, kind) {
  const toast = document.createElement("div");
  toast.className = "toast" + (kind ? " toast-" + kind : "");
  toast.textContent = message;
  toastContainerEl.appendChild(toast);

  // 誘導メッセージ（kind あり）は長文なので、CSS側の消灯タイミングに合わせて長く残す
  setTimeout(() => {
    toast.remove();
  }, kind ? 4900 : 2800);
}

