// 非消耗型のアプリ内課金を1つだけ持つ。サブスクではない。
//
// 【所有状態を自分で保存する理由】
// このアプリは検証サーバー（iaptic 等）を持たない構成なので、プラグインは
// 起動時に過去の購入を把握できない（取引が届くのは購入・復元の直後だけ）。
// プラグイン任せにすると起動のたびに「買ったのに広告が出る」状態が発生する。
// そのため approved を受けた時点で端末に印を付け、次回以降はそれを信じる。
