// 「見る」を押したときの入口。広告を挟むかどうかはここで決まる。
async function requestHint() {
  SoundManager.play("tap");
  if (!Ads.available()) {      // ブラウザ・VIP購入者：広告なしでそのまま開く
    revealHint();
    return;
  }
  setHintButtonBusy(true);
  let outcome = "unavailable";
  try {
    outcome = await Ads.showRewarded();
  } catch (e) {
    outcome = "unavailable";
  }
  setHintButtonBusy(false);

  if (outcome === "dismissed") {
    // 自分で途中でやめた場合だけ開かない。報酬は渡さない。
    showToast("動画が最後まで再生されなかったため、ヒントは開きません。");
    return;
  }
  // "rewarded"（最後まで見た）と "unavailable"（広告を出せなかった）は開く。
  // 広告が出せないのはこちらの都合であって、遊べなくする理由にならない。
  revealHint();
}

