// --- サウンド（Web Audio 合成・音源ファイル不要） ---
// mp3 を一切持たない構成にしている。理由:
//  ・音源ファイルが無い環境で 404 を出し続ける事故が構造的に起きない
//  ・オフライン／USBコピー／file:// でもそのまま鳴る
//  ・追加のダウンロードが無いので起動が遅くならない
// 音を出せない環境（AudioContext 非対応・自動再生ブロック）では静かに無音へ倒す。
const SoundManager = {
  muted: false,
  ctx: null,
  ready: false,

  init() {
    this.muted = SafeStorage.get("mystery_mute") === "true";
    this.updateMuteUI();
    // スマホは利用者が触るまで音を出せない。最初の操作で解錠する。
    const unlock = () => this.unlock();
    document.addEventListener("pointerdown", unlock, { once: true });
    document.addEventListener("touchend", unlock, { once: true });
    document.addEventListener("click", unlock, { once: true });
  },

  unlock() {
    if (this.ready) return;
    try {
      const AC = window.AudioContext || window.webkitAudioContext;
      if (!AC) return;              // 非対応環境ではずっと無音のまま進む
      this.ctx = new AC();
      if (this.ctx.state === "suspended") {
        const r = this.ctx.resume();
        if (r && typeof r.catch === "function") r.catch(() => {});
      }
      this.ready = true;
    } catch (e) {
      this.ctx = null;
    }
  },

  // 1音の最小単位。sweepTo を渡すと周波数が滑る（不正解のシュンという音に使う）
  tone(type, freq, dur, gain, delay, sweepTo) {
    if (!this.ctx) return;
    try {
      const t0 = this.ctx.currentTime + (delay || 0);
      const osc = this.ctx.createOscillator();
      const amp = this.ctx.createGain();
      osc.type = type;
      osc.frequency.setValueAtTime(freq, t0);
      if (sweepTo) osc.frequency.exponentialRampToValueAtTime(sweepTo, t0 + dur);
      // 立ち上がりと減衰を必ず付ける。いきなり切るとプチッとノイズが乗る。
      amp.gain.setValueAtTime(0.0001, t0);
      amp.gain.exponentialRampToValueAtTime(gain, t0 + 0.012);
      amp.gain.exponentialRampToValueAtTime(0.0001, t0 + dur);
      osc.connect(amp);
      amp.connect(this.ctx.destination);
      osc.start(t0);
      osc.stop(t0 + dur + 0.03);
    } catch (e) { /* 1音鳴らないだけ。進行は止めない */ }
  },

  play(name) {
    if (this.muted) return;
    this.unlock();
    if (!this.ctx) return;
    if (name === "tap") {
      this.tone("triangle", 620, 0.06, 0.14);
    } else if (name === "pick") {           // 指摘位置を置いたとき
      this.tone("triangle", 880, 0.07, 0.18);
      this.tone("triangle", 1320, 0.09, 0.10, 0.05);
    } else if (name === "correct") {        // 正解：上昇アルペジオ
      [523.25, 659.25, 783.99, 1046.5].forEach((f, i) => {
        this.tone("triangle", f, 0.32, 0.16, i * 0.085);
      });
    } else if (name === "wrong") {          // 不正解：下降するうなり
      this.tone("sawtooth", 220, 0.26, 0.13, 0, 110);
      this.tone("sawtooth", 165, 0.32, 0.10, 0.06, 82);
    } else if (name === "deny") {           // 操作できないとき
      this.tone("square", 170, 0.10, 0.07);
    } else if (name === "clear") {          // 事件解決
      [523.25, 659.25, 783.99, 1046.5, 1318.5].forEach((f, i) => {
        this.tone("triangle", f, 0.45, 0.15, i * 0.10);
      });
    }
  },

  // 呼び出し側は従来どおり "se_tap.mp3" のような名前で呼べる（旧APIとの互換）
  playSE(src) {
    let k = String(src);
    if (k.indexOf("se_") === 0) k = k.slice(3);
    const dot = k.indexOf(".");
    if (dot > 0) k = k.slice(0, dot);
    this.play(k);
  },

  // BGMは持たない方針。呼ばれても何もしない（呼び出し側を書き換えずに済ませる）
  // --- BGM（音源ファイルなし。ドローン＋まばらな単音）---
  // 常時鳴らす音は、うるさいと即ミュートされる。
  // 低い持続音を薄く敷き、その上に数秒に1音だけ落とす。旋律は作らない。
  bgm: { kind: null, timer: null, master: null, nodes: [], next: 0 },

  // 曲ごとの設定。scale は Hz。
  BGM_KINDS: {
    lobby: {
      drone: [146.83, 220.00],          // D3 + A3
      scale: [293.66, 329.63, 349.23, 440.00, 523.25],
      gapMin: 1.8, gapMax: 3.2, decay: 2.6, wave: "sine",  droneGain: 0.020, noteGain: 0.055
    },
    investigate: {
      drone: [110.00, 164.81],          // A2 + E3（5度。濁らせない）
      scale: [261.63, 293.66, 349.23, 392.00, 523.25],
      gapMin: 2.6, gapMax: 4.8, decay: 3.4, wave: "triangle", droneGain: 0.016, noteGain: 0.042
    }
  },

  setBGM(kind) {
    if (this.bgm.kind === kind) return;
    this.stopBGM();
    this.bgm.kind = kind;
    if (this.muted) return;            // ミュート中は予約だけ覚えて鳴らさない
    this.startBGM();
  },

  startBGM() {
    const conf = this.BGM_KINDS[this.bgm.kind];
    if (!conf) return;
    this.unlock();
    if (!this.ctx || this.bgm.master) return;
    try {
      const ctx = this.ctx;
      const master = ctx.createGain();
      master.gain.setValueAtTime(0.0001, ctx.currentTime);
      // 立ち上げは4秒かけて。いきなり鳴ると画面遷移の邪魔になる。
      master.gain.linearRampToValueAtTime(1, ctx.currentTime + 4);
      const lp = ctx.createBiquadFilter();
      lp.type = "lowpass";
      lp.frequency.setValueAtTime(1800, ctx.currentTime);
      lp.connect(ctx.destination);
      master.connect(lp);
      this.bgm.master = master;

      conf.drone.forEach((f, i) => {
        const osc = ctx.createOscillator();
        const g = ctx.createGain();
        osc.type = "sine";
        osc.frequency.setValueAtTime(f, ctx.currentTime);
        // わずかにずらして揺らぎを出す。完全に同期すると機械音に聞こえる。
        osc.detune.setValueAtTime(i === 0 ? -4 : 5, ctx.currentTime);
        g.gain.setValueAtTime(conf.droneGain, ctx.currentTime);
        osc.connect(g); g.connect(master);
        osc.start();
        this.bgm.nodes.push(osc);
      });

      this.bgm.next = ctx.currentTime + 1.2;
      this.bgm.timer = setInterval(() => this.scheduleBGM(), 500);
      this.scheduleBGM();
    } catch (e) {
      this.stopBGM();                  // 鳴らせない環境では黙って無音のまま進む
    }
  },

  // 500msごとに、1.5秒先までの単音を予約する。
  scheduleBGM() {
    const conf = this.BGM_KINDS[this.bgm.kind];
    if (!conf || !this.ctx || !this.bgm.master) return;
    try {
      const ctx = this.ctx;
      const until = ctx.currentTime + 1.5;
      let guard = 0;
      while (this.bgm.next < until && guard++ < 8) {
        const t0 = Math.max(this.bgm.next, ctx.currentTime + 0.05);
        const f = conf.scale[Math.floor(Math.random() * conf.scale.length)];
        const osc = ctx.createOscillator();
        const g = ctx.createGain();
        osc.type = conf.wave;
        osc.frequency.setValueAtTime(f, t0);
        g.gain.setValueAtTime(0.0001, t0);
        g.gain.linearRampToValueAtTime(conf.noteGain, t0 + 0.35);
        g.gain.linearRampToValueAtTime(0.0001, t0 + conf.decay);
        osc.connect(g); g.connect(this.bgm.master);
        osc.start(t0);
        osc.stop(t0 + conf.decay + 0.1);
        this.bgm.next = t0 + conf.gapMin + Math.random() * (conf.gapMax - conf.gapMin);
      }
    } catch (e) { /* 1音抜けるだけ。曲は続ける */ }
  },

  stopBGM() {
    if (this.bgm.timer) { clearInterval(this.bgm.timer); this.bgm.timer = null; }
    try {
      if (this.bgm.master && this.ctx) {
        const t = this.ctx.currentTime;
        // 0.5秒でフェードしてから止める。ぶつ切りはノイズになる。
        this.bgm.master.gain.cancelScheduledValues(t);
        this.bgm.master.gain.setValueAtTime(this.bgm.master.gain.value || 0.0001, t);
        this.bgm.master.gain.linearRampToValueAtTime(0.0001, t + 0.5);
      }
      const nodes = this.bgm.nodes.slice();
      setTimeout(() => nodes.forEach(n => { try { n.stop(); } catch (e) {} }), 600);
    } catch (e) { /* 落ちても進行は止めない */ }
    this.bgm.nodes = [];
    this.bgm.master = null;
  },

  // タブが隠れているあいだは鳴らさない。電池を食うだけで誰も聞いていない。
  suspendBGM() {
    const kind = this.bgm.kind;
    this.stopBGM();
    this.bgm.kind = kind;
  },

  resumeBGM() {
    if (this.muted || !this.bgm.kind || this.bgm.master) return;
    this.startBGM();
  },

  // 既存の呼び出し用。引数なしならロビー曲。
  playBGM() { this.setBGM("lobby"); },

  toggleMute() {
    this.muted = !this.muted;
    SafeStorage.set("mystery_mute", this.muted);
    if (this.muted) {
      this.suspendBGM();
    } else {
      this.play("tap");
      this.resumeBGM();
    }
    this.updateMuteUI();
  },

  updateMuteUI() {
    const onPaths = document.querySelectorAll(".speaker-on-path");
    const offPaths = document.querySelectorAll(".speaker-off-path");
    onPaths.forEach(el => el.style.display = this.muted ? "none" : "block");
    offPaths.forEach(el => el.style.display = this.muted ? "block" : "none");
  }
};

