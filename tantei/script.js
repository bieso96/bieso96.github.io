// --- ズームと位置のリセット ---
let zoomResetTimers = [];
function resetZoomLayout(animate = false) {
  scale = 1.0;
  panX = 0;
  panY = 0;

  // 連続で呼ばれたとき（等倍ボタン連打・ステージ切り替え直後など）に
  // 古いタイマーが後から発火して、アニメ中の中途半端な矩形を等倍として
  // 記録してしまうのを防ぐ。
  zoomResetTimers.forEach(clearTimeout);
  zoomResetTimers = [];

  if (animate) {
    imageWrapperEl.style.transition = "transform 0.25s cubic-bezier(0.25, 1, 0.5, 1)";
    zoomResetTimers.push(setTimeout(() => {
      imageWrapperEl.style.transition = "none";
    }, 250));
  } else {
    imageWrapperEl.style.transition = "none";
  }

  imageWrapperEl.style.transform = "translate3d(0px, 0px, 0) scale(1)";

  // 計測は transition が終わってから。動いている最中に測ると
  // 途中の縮んだサイズを等倍として覚えてしまう。
  zoomResetTimers.push(setTimeout(() => {
    recordInitialImageBounds();
    updatePinPosition();
  }, animate ? 280 : 50));
}

// 等倍サイズが未計測（画像未読み込み・画面が隠れていた等）なら測り直す。
// ここが 0 のままだとパン上限が 0 になり、拡大しても動かせなくなる。
function ensureImageBounds() {
  if (!initialImageRect || !initialImageRect.width || !initialImageRect.height) {
    recordInitialImageBounds();
  }
  return !!(initialImageRect && initialImageRect.width);
}

// パンを可動域に収めて transform を書き込む（クランプ処理の唯一の置き場所）
function applyTransform() {
  ensureImageBounds();
  const maxPanX = ((scale - 1) * initialImageRect.width) / 2;
  const maxPanY = ((scale - 1) * initialImageRect.height) / 2;
  panX = Math.max(-maxPanX, Math.min(maxPanX, panX));
  panY = Math.max(-maxPanY, Math.min(maxPanY, panY));
  imageWrapperEl.style.transform = `translate3d(${panX}px, ${panY}px, 0) scale(${scale})`;
  updatePinPosition();
}

// 画像の等倍サイズ記録
function recordInitialImageBounds() {
  const currentScale = scale;
  const currentPanX = panX;
  const currentPanY = panY;

  imageWrapperEl.style.transform = "translate3d(0px, 0px, 0) scale(1)";
  initialImageRect = stageImageEl.getBoundingClientRect();

  imageWrapperEl.style.transform = `translate3d(${currentPanX}px, ${currentPanY}px, 0) scale(${currentScale})`;
}

// --- ゾーン採寸モード（開発用） ---
// index.html?zone=1 で有効。画像の上をドラッグすると矩形を引け、
// targets / decoys にそのまま貼れる形の座標を表示する。
// 新しい話を足すときに座標を目分量で書くと、解説と正解位置がズレる事故が起きる。
// （実際に第3話がそれで「解説は雪面の穴・判定は軒先だけ」になっていた）
const ZoneEditor = {
  active: false,
  drawing: false,
  x0: 0, y0: 0,
  boxEl: null,
  panelEl: null,

  init() {
    const params = new URLSearchParams(location.search);
    if (params.get("zone") !== "1") return;
    this.active = true;

    this.boxEl = document.createElement("div");
    this.boxEl.className = "zone-box";
    imageViewportEl.appendChild(this.boxEl);

    this.panelEl = document.createElement("div");
    this.panelEl.className = "zone-panel";
    this.panelEl.textContent = "画像の上をドラッグして範囲を囲ってください";
    document.body.appendChild(this.panelEl);
  },

  // 画面座標 → 画像内の％。判定に使う値と同じ出し方にすること。
  toPct(clientX, clientY) {
    const r = stageImageEl.getBoundingClientRect();
    if (!r.width || !r.height) return null;
    return {
      x: Math.max(0, Math.min(100, ((clientX - r.left) / r.width) * 100)),
      y: Math.max(0, Math.min(100, ((clientY - r.top) / r.height) * 100))
    };
  },

  start(e) {
    const p = this.toPct(e.clientX, e.clientY);
    if (!p) return;
    this.drawing = true;
    this.x0 = p.x; this.y0 = p.y;
    this.draw(p.x, p.y);
  },

  move(e) {
    if (!this.drawing) return;
    const p = this.toPct(e.clientX, e.clientY);
    if (p) this.draw(p.x, p.y);
  },

  end() {
    if (!this.drawing) return;
    this.drawing = false;
    const z = this.last;
    if (!z) return;
    const line = `{ xMin: ${z.xMin}, xMax: ${z.xMax}, yMin: ${z.yMin}, yMax: ${z.yMax} }`;
    const areaPct = ((z.xMax - z.xMin) * (z.yMax - z.yMin) / 100).toFixed(1);
    this.panelEl.textContent = line + "  ／ 面積 " + areaPct + "%";
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(line).catch(() => {});
    }
  },

  draw(x, y) {
    const z = {
      xMin: Math.round(Math.min(this.x0, x)), xMax: Math.round(Math.max(this.x0, x)),
      yMin: Math.round(Math.min(this.y0, y)), yMax: Math.round(Math.max(this.y0, y))
    };
    this.last = z;
    const r = stageImageEl.getBoundingClientRect();
    const v = imageViewportEl.getBoundingClientRect();
    this.boxEl.style.display = "block";
    this.boxEl.style.left = (r.left - v.left + r.width * z.xMin / 100) + "px";
    this.boxEl.style.top = (r.top - v.top + r.height * z.yMin / 100) + "px";
    this.boxEl.style.width = (r.width * (z.xMax - z.xMin) / 100) + "px";
    this.boxEl.style.height = (r.height * (z.yMax - z.yMin) / 100) + "px";
  }
};

// --- Pinch-to-Zoom / Pan ジェスチャエンジンの実装 ---
function setupGestureZoom() {
  const viewport = imageViewportEl;

  // ポインタ捕捉は「そのIDがもうアクティブでない」だけで例外を投げる。
  // 指がウィンドウ外で離れた直後などに普通に起きるので、必ず握りつぶす。
  const capture = (id) => { try { viewport.setPointerCapture(id); } catch (e) {} };
  const release = (id) => { try { viewport.releasePointerCapture(id); } catch (e) {} };

  // 取りこぼしたポインタを全部捨てる。
  // これが無いと「離したはずの指」が Map に残り続け、以後 size が 2 のままになって
  // 1本指のドラッグもタップも効かなくなる（＝タッチIDが積み上がる状態）。
  const clearPointers = () => {
    activePointers.forEach((_, id) => release(id));
    activePointers.clear();
    prevDiff = -1;
    didMove = false;
  };

  // 1本指ドラッグの基準を「今この瞬間の指の位置と今のパン量」で取り直す
  const rebaseDrag = (ev) => {
    dragStartX = ev.clientX;
    dragStartY = ev.clientY;
    initialPanX = panX;
    initialPanY = panY;
  };

  // 2本指ピンチの基準を「今この瞬間の2点」で取り直す
  const rebasePinch = (pts) => {
    prevDiff = Math.hypot(pts[0].clientX - pts[1].clientX, pts[0].clientY - pts[1].clientY);
    initialScale = scale;
    initialPanX = panX;
    initialPanY = panY;
    pinchStartX = (pts[0].clientX + pts[1].clientX) / 2;
    pinchStartY = (pts[0].clientY + pts[1].clientY) / 2;
  };

  viewport.addEventListener("pointerdown", (e) => {
    if (isModalOpen) return;
    if (ZoneEditor.active) { ZoneEditor.start(e); return; }
    activePointers.set(e.pointerId, e);

    if (activePointers.size === 1) {
      didMove = false;
      rebaseDrag(e);
    } else {
      // 2本目以降が触れた時点でタップ判定は打ち切る（指摘ピンの誤配置を防ぐ）
      didMove = true;
      if (activePointers.size === 2) rebasePinch(Array.from(activePointers.values()));
    }
    capture(e.pointerId);
  });

  viewport.addEventListener("pointermove", (e) => {
    if (ZoneEditor.active) { ZoneEditor.move(e); return; }
    if (!activePointers.has(e.pointerId) || isModalOpen) return;
    activePointers.set(e.pointerId, e);

    if (activePointers.size === 1) {
      const dist = Math.hypot(e.clientX - dragStartX, e.clientY - dragStartY);
      if (dist > TAP_SLOP) didMove = true;

      if (scale > 1.0 && didMove && canTransformImage()) {
        panX = initialPanX + (e.clientX - dragStartX);
        panY = initialPanY + (e.clientY - dragStartY);
        applyTransform();
      }
    } else if (activePointers.size === 2) {
      const pts = Array.from(activePointers.values());
      const curDiff = Math.hypot(pts[0].clientX - pts[1].clientX, pts[0].clientY - pts[1].clientY);

      if (prevDiff > 0 && canTransformImage()) {
        scale = Math.max(1.0, Math.min(4.0, initialScale * (curDiff / prevDiff)));

        const midX = (pts[0].clientX + pts[1].clientX) / 2;
        const midY = (pts[0].clientY + pts[1].clientY) / 2;
        panX = initialPanX + (midX - pinchStartX);
        panY = initialPanY + (midY - pinchStartY);
        applyTransform();
      }
    }
  });

  // isTap=false は pointercancel（システムに取り上げられた）用。指摘にはしない。
  const endPointer = (e, isTap) => {
    if (!activePointers.has(e.pointerId)) return;

    activePointers.delete(e.pointerId);
    release(e.pointerId);

    // 最後の1本が「動かずに」離れたときだけタップ＝指摘とみなす
    if (isTap && activePointers.size === 0 && !didMove && !isModalOpen) {
      const targetElement = document.elementFromPoint(e.clientX, e.clientY);
      if (targetElement === stageImageEl) {
        handleImageTap(e.clientX, e.clientY);
      }
    }

    const rest = Array.from(activePointers.values());
    if (rest.length >= 2) {
      // 3本→2本：基準を取り直さないと、残った2点の間隔で倍率が突然跳ぶ
      rebasePinch(rest);
    } else if (rest.length === 1) {
      // 2本→1本：基準を取り直さないと、残った指の座標差がそのままパンに乗って画像が飛ぶ
      prevDiff = -1;
      rebaseDrag(rest[0]);
      didMove = true;   // ピンチの余韻での指離しをタップと誤認させない
    } else {
      prevDiff = -1;
      if (scale <= 1.01) resetZoomLayout(true);
    }
  };

  viewport.addEventListener("pointerup", (e) => {
    if (ZoneEditor.active) { ZoneEditor.end(); return; }
    endPointer(e, true);
  });
  viewport.addEventListener("pointercancel", (e) => endPointer(e, false));

  // pointerout は「ジェスチャーの終わり」ではないので、ここでは使わない。
  // pointerout は子要素（img・指摘ピン）へ移っただけでも発火し、親までバブリングする。
  // setPointerCapture / releasePointerCapture の前後にも境界イベントとして発火する。
  // 旧実装はこれを pointerup と同じ終了処理に繋いでいたため、
  // 指を動かしている最中に勝手にジェスチャーが打ち切られ、
  // まだ動いていない状態（didMove=false）ならその場でタップ＝指摘として確定してしまう。
  // 指が画面外へ抜けた場合は pointercancel と、下の blur / visibilitychange で回収する。
  window.addEventListener("blur", clearPointers);
  document.addEventListener("visibilitychange", () => {
    if (document.hidden) {
      clearPointers();
      SoundManager.suspendBGM();     // 誰も聞いていない音で電池を使わない
    } else {
      SoundManager.resumeBGM();
    }
  });
}

// --- スクリーン座標から画像座標（%）への逆変換 ---
function handleImageTap(clientX, clientY) {
  // 表示中の画像矩形（transform 適用後）をそのまま基準にする。
  // pan と scale を手で打ち消す計算は、transform-origin が
  // ビューポート中心と一致していることを前提にしていた。
  // 実際の原点はラッパー中心で、セーフエリアの左右差やパディングでズレるため
  // 拡大時の指摘位置が斜めにずれる。ここは表示矩形からの相対比だけで足りる。
  // updatePinPosition() と同じ矩形を見るので、タップ→ピン表示が必ず一致する。
  const rect = stageImageEl.getBoundingClientRect();

  // 画像が未読み込み・非表示だと 0 になる。ゼロ割りで NaN を入れない。
  if (!rect.width || !rect.height) {
    showToast("画像の読み込みが終わっていません。少し待ってからタップしてください。");
    return;
  }

  // 供述型では絵は「見るためのもの」。タップで指摘位置は置かない。
  // シートが開いていれば閉じて、写真を遮らないようにする。
  if (isStatementMode(stages[currentStageIndex])) {
    if (openSheet) hideSheet();
    return;
  }

  selectedX = Math.max(0, Math.min(100, ((clientX - rect.left) / rect.width) * 100));
  selectedY = Math.max(0, Math.min(100, ((clientY - rect.top) / rect.height) * 100));

  updatePinPosition();
  updateAccuseButton();

  SoundManager.play("pick");
}

