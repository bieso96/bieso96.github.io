// ここで握っておかないと init() が丸ごと止まり、白画面になる。
const SafeStorage = {
  get(key) {
    try { return localStorage.getItem(key); } catch (e) { return null; }
  },
  set(key, value) {
    try { localStorage.setItem(key, String(value)); return true; } catch (e) { return false; }
  }
};

