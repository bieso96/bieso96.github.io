function loadProgress() {
  // 壊れた値（NaN・範囲外・JSON以外）が入っていても必ず遊べる状態から始める。
  // 以前は parseInt が NaN になると全ステージがロックされたまま復帰できなかった。
  const savedUnlocked = parseInt(SafeStorage.get("mystery_unlocked_stage"), 10);
  unlockedStageIndex = Number.isFinite(savedUnlocked)
    ? Math.max(0, Math.min(savedUnlocked, stages.length - 1))
    : 0;

  clearedStageRecords = {};
  const savedCleared = SafeStorage.get("mystery_stage_records");
  if (savedCleared) {
    try {
      const parsed = JSON.parse(savedCleared);
      if (parsed && typeof parsed === "object") clearedStageRecords = parsed;
    } catch (e) {
      clearedStageRecords = {};
    }
  }
}

